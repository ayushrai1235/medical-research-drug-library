import ExcelJS from 'exceljs';

export interface ActivityExportRow {
  id: string;
  createdAt: string;
  displayName: string;
  action: string;
  primaryDrug: string;
  relatedDrugs: string;
  category: string;
  downloadType: string;
  details: string;
}

export function sanitizeCellValue(val: any): any {
  if (typeof val === 'string') {
    const trimmed = val.trim();
    if (/^[=+\-@\t\r]/.test(trimmed)) {
      return `'${val}`;
    }
  }
  return val;
}

export async function generateActivityExcel(
  rows: ActivityExportRow[],
  summaryData: {
    totalEvents: number;
    pdfViews: number;
    individualDownloads: number;
    zipDownloads: number;
    comparisonDownloads: number;
    generatedBy: string;
  }
): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Medical Research Drug Library';
  workbook.created = new Date();

  // 1. Activity Logs Worksheet
  const sheet = workbook.addWorksheet('Activity Events', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });

  sheet.columns = [
    { header: 'Event ID', key: 'id', width: 38 },
    { header: 'Timestamp (UTC)', key: 'createdAt', width: 22 },
    { header: 'User / Researcher', key: 'displayName', width: 25 },
    { header: 'Action', key: 'action', width: 28 },
    { header: 'Primary Drug', key: 'primaryDrug', width: 20 },
    { header: 'Related Drugs', key: 'relatedDrugs', width: 30 },
    { header: 'Category', key: 'category', width: 25 },
    { header: 'Download Type', key: 'downloadType', width: 18 },
    { header: 'Details (JSON)', key: 'details', width: 40 },
  ];

  // Header style
  sheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  sheet.getRow(1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF1E3A8A' }, // Primary Medical Blue
  };
  sheet.getRow(1).alignment = { vertical: 'middle', horizontal: 'center' };
  sheet.getRow(1).height = 28;

  for (const r of rows) {
    sheet.addRow({
      id: sanitizeCellValue(r.id),
      createdAt: sanitizeCellValue(r.createdAt),
      displayName: sanitizeCellValue(r.displayName),
      action: sanitizeCellValue(r.action),
      primaryDrug: sanitizeCellValue(r.primaryDrug),
      relatedDrugs: sanitizeCellValue(r.relatedDrugs),
      category: sanitizeCellValue(r.category),
      downloadType: sanitizeCellValue(r.downloadType),
      details: sanitizeCellValue(r.details),
    });
  }

  // Auto-border on rows
  sheet.eachRow((row, rowNumber) => {
    if (rowNumber > 1) {
      row.alignment = { vertical: 'middle' };
      row.height = 20;
    }
  });

  // 2. Summary Worksheet
  const summarySheet = workbook.addWorksheet('Summary');
  summarySheet.columns = [
    { header: 'Metric', key: 'metric', width: 35 },
    { header: 'Value', key: 'value', width: 30 },
  ];

  summarySheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  summarySheet.getRow(1).fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF0F766E' }, // Accent Teal
  };
  summarySheet.getRow(1).height = 28;

  summarySheet.addRow({ metric: 'Export Generated At', value: new Date().toISOString() });
  summarySheet.addRow({ metric: 'Export Generated By', value: sanitizeCellValue(summaryData.generatedBy) });
  summarySheet.addRow({ metric: 'Total Exported Events', value: summaryData.totalEvents });
  summarySheet.addRow({ metric: 'PDF Views (pdf_viewed)', value: summaryData.pdfViews });
  summarySheet.addRow({ metric: 'Individual Downloads (pdf_downloaded)', value: summaryData.individualDownloads });
  summarySheet.addRow({ metric: 'Multi-PDF ZIP Downloads (zip_downloaded)', value: summaryData.zipDownloads });
  summarySheet.addRow({ metric: 'Comparison PDF Downloads (comparison_pdf_downloaded)', value: summaryData.comparisonDownloads });

  summarySheet.eachRow((row, rowNumber) => {
    if (rowNumber > 1) {
      row.height = 22;
      row.alignment = { vertical: 'middle' };
    }
  });

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}
